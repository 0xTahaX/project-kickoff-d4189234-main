// قوانین اعتبارسنجی فرم‌ها. هر تابع پیام خطا را برمی‌گرداند، یا رشته‌ی خالی اگر مقدار درست باشد.
// توجه: این بررسی فقط برای راحتی کاربر است؛ سرور باید دوباره همه‌چیز را بررسی کند.
const V = {
  // بررسی نام؛ اگر required باشد خالی بودنش خطاست
  name(v, required) {
    v = v.trim();
    if (!v) return required ? "این فیلد الزامی است." : "";
    return v.length > 50 ? "حداکثر ۵۰ کاراکتر مجاز است." : "";
  },
  // بررسی قالب ایمیل
  email(v) {
    v = v.trim();
    if (!v) return "ایمیل را وارد کنید.";
    return /^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/.test(v) ? "" : "قالب ایمیل درست نیست.";
  },
  // سیاست گذرواژه: حداقل ۱۰ کاراکتر، دست‌کم یک حرف و یک عدد
  password(v) {
    if (v.length < 10) return "گذرواژه باید حداقل ۱۰ کاراکتر باشد.";
    if (!/[A-Za-z\u0600-\u06FF]/.test(v)) return "گذرواژه باید شامل حرف باشد.";
    return /\d|[۰-۹]/.test(v) ? "" : "گذرواژه باید شامل عدد باشد.";
  },
  // بررسی یکسان بودن گذرواژه و تکرار آن
  confirm(p, c) {
    return p === c ? "" : "گذرواژه و تکرار آن یکسان نیستند.";
  },
};
if (typeof module !== "undefined") module.exports = V;
